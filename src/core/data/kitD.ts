const tricksZone = (radius: number, duration: number, perTick: number, attackMult: number): Effect[] => [
  {
    t: 'zone',
    radius,
    duration,
    tickEvery: 0.5,
    at: 'caster',
    follow: true,
    channel: true,
    affects: 'enemies',
    effects: [{ t: 'damage', amount: perTick, dmgType: 'physical', attackMult }],
  },
  { t: 'custom', id: 'invulnerable', params: { duration } },
];

const burningArmy = (radius: number, duration: number, perTick: number, attackMult: number): Effect[] => [
  {
    t: 'zone',
    radius,
    duration,
    tickEvery: 0.5,
    at: 'target',
    affects: 'enemies',
    delay: 0.3,
    effects: [{ t: 'damage', amount: perTick, dmgType: 'physical', attackMult }],
  },
];

const haunt = (dps: number, duration: number, slow: number): Effect[] => [
  { t: 'dot', dps, duration, dmgType: 'physical' },
  { t: 'slow', pct: slow, duration },
];

const pierceTheVeil = (dmgPct: number, amp: number, flat: number, duration: number): Effect[] => [
  { t: 'buff', stat: 'damagePct', value: dmgPct, duration },
  { t: 'buff', stat: 'spellAmp', value: amp, duration },
  { t: 'buff', stat: 'damage', value: flat, duration },
  { t: 'buff', stat: 'evasion', value: 40, duration }, // ethereal: physical attacks pass through her
];

